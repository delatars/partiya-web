/** Какой организации принадлежит завод из фикстур каталога.
 *
 * ⚠ В контракте этой связи нет: `OfferFactory.id` — номер завода в каталоге, а `orgId`
 * — идентификатор организации. У бэка это одна и та же сущность (`FactoryProfile`
 * принадлежит `Organization`), здесь — словарь на два значения (Q-S2). */
export function factoryOrgIdOf(factoryId: number): string | null {
  return factoryId === DEMO_FACTORY_ID ? DEMO_ORG_IDS.volna : null;
}

/** Есть ли у организации демо-наполнение. Новая компания из формы регистрации — пустая,
    и именно на ней видно пустые состояния из макета `state-empty`. */
export function isDemoOrg(orgId: string | null | undefined): boolean {
  return orgId === DEMO_ORG_IDS.kora || orgId === DEMO_ORG_IDS.volna;
}

